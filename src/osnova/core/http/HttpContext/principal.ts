/**
 * Контракт «текущего субъекта запроса» в `ctx.state`.
 *
 * Это единственная точка согласования между слоем аутентификации (прикладной
 * `@Authorize`-check кладёт принципала в `ctx.state`) и теми частями ядра,
 * которым нужна персонализация по пользователю (например, output-кэш с
 * `varyByUser`/`varyByClaim`). Ключ и форма объявлены здесь, в ядре, поэтому
 * прикладной код зависит от ядра — а не наоборот.
 */

/** Ключ `ctx.state`, под которым хранится {@link RequestPrincipal}. */
export const PRINCIPAL_STATE_KEY = "auth:principal";

/**
 * Минимальная форма принципала, на которую опирается ядро. Конкретная реализация
 * (вид токена, набор claim'ов и т. п.) — за прикладным слоем; ядру достаточно
 * этих необязательных полей.
 */
export interface RequestPrincipal {
  /** Идентификатор субъекта (`sub`); используется output-кэшем для `varyByUser`. */
  readonly subject?: string;
  /** Опциональный поиск claim'а по типу; используется для `varyByClaim`. */
  findFirst?(claimType: string): string | undefined;
}
